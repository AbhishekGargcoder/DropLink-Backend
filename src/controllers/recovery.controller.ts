import type { RequestHandler } from "express";
import {
    createDeviceRecoverySession,
    confirmDeviceRecovery
} from "../services/recovery.service.js";

export const createRecovery: RequestHandler = async (req, res, next) => {
    try {
        const hostDeviceId = res.locals.device.id; // laptop's deviceId from the authenticated request
        const { targetDeviceId } = req.body;

        if (
            typeof targetDeviceId !== "string" ||
            !/^[0-9a-f]{8}-[0-9a-f]{4}-[1-8][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/i.test(targetDeviceId)
        ) {
            res.status(400).json({
                success: false,
                message: "A valid target device ID is required"
            });
            return;
        }

        const session = await createDeviceRecoverySession({
            hostDeviceId,
            targetDeviceId
        });

        res.status(201).json({
            success: true,
            message: "Phone recovery session created",
            data: session
        });
    } catch (error) {
        next(error);
    }
};

export const confirmRecovery: RequestHandler = async (req, res, next) => {
    try {
        // Extract the recovery token from the request body.
        const { qrToken } = req.body; // new temporary token generated by the laptop and scanned by the phone

        if (
            typeof qrToken !== "string" ||
            qrToken.length < 20 ||
            qrToken.length > 200
        ) {
            res.status(400).json({
                success: false,
                message: "A valid recovery QR token is required"
            });
            return;
        }

        const result = await confirmDeviceRecovery({ qrToken });

        res.status(200).json({
            success: true,
            message: "Phone recovered successfully",
            data: result
        });
    } catch (error) {
        next(error);
    }
};
